
//***************************************************************************
// Utf8Literal.h : 소스 문자 집합과 상관없이 UTF-8 바이트를 내는 문자열 리터럴
//
//***************************************************************************

#ifndef UTF8LITERAL_H
#define UTF8LITERAL_H

//***************************************************************************
// @brief U8("한글")은 컴파일러의 실행 문자 집합(MSVC 기본은 시스템 코드 페이지, 한국어 Windows에서는 CP949)과 상관없이
//        항상 UTF-8 바이트를 만드는 const char* 리터럴이다.
// @details 한글이 든 일반 리터럴("...")은 /utf-8 옵션이 없으면 CP949로 변환되어, 생성 파일에 쓰면 깨진 UTF-8이 되고
//          콘솔(UTF-8)에 출력해도 깨진다. 그래서 한글이 든 리터럴은 모두 U8()로 감싼다. 소스 파일은 BOM 있는 UTF-8이어야 한다.
//          (엑셀에서 읽은 문자열은 xlnt가 UTF-8로 주므로 영향이 없다.) C++20의 char8_t 모드에서는 const char*로 바꿔 준다.
//***************************************************************************
#if defined(__cpp_char8_t)
#define U8(s) (reinterpret_cast<const char*>(u8##s))
#else
#define U8(s) (u8##s)
#endif

#endif // ndef UTF8LITERAL_H