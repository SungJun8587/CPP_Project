#ifndef ZONEMATH_H
#define ZONEMATH_H

//***************************************************************************
// @brief 존 평면 좌표(x, y). 높이(z)는 현재 단계에서 다루지 않는다.
//***************************************************************************
struct Vec2
{
	float x = 0.0f;		// X 좌표
	float y = 0.0f;		// Y 좌표
};

//***************************************************************************
// @brief 두 좌표 사이 거리의 제곱을 반환합니다. (sqrt 비용 회피용)
// @param a 좌표 A
// @param b 좌표 B
// @return 거리의 제곱
//***************************************************************************
inline float DistanceSq(const Vec2& a, const Vec2& b)
{
	const float dx = a.x - b.x;
	const float dy = a.y - b.y;
	return dx * dx + dy * dy;
}

#endif // ndef ZONEMATH_H
